values ('promos', 'promos', true)
on conflict (id) do nothing;

drop policy if exists promos_bucket_read on storage.objects;
create policy promos_bucket_read on storage.objects
  for select using (bucket_id = 'promos');

drop policy if exists promos_bucket_write on storage.objects;
create policy promos_bucket_write on storage.objects
  for all using (bucket_id = 'promos' and public.is_agent())
          with check (bucket_id = 'promos' and public.is_agent());

