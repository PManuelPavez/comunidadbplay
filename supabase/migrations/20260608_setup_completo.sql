-- =========================================================
-- 3) CHAT EN VIVO — chat_conversations + chat_messages
--    Rol: chat visitante <-> agente en tiempo real.
--    Visitante (auth anónima) solo ve/escribe SU conversación;
--    el agente ve/escribe todas.
-- =========================================================
create table if not exists public.chat_conversations (
  id          uuid primary key default gen_random_uuid(),
  user_id     uuid not null default auth.uid(),
  province    text,
  status      text not null default 'open',   -- open | agent | closed
  created_at  timestamptz default now(),
  last_at     timestamptz default now()
);

create table if not exists public.chat_messages (
  id              uuid primary key default gen_random_uuid(),
  conversation_id uuid not null references public.chat_conversations(id) on delete cascade,
  sender          text not null check (sender in ('visitor','agent','bot')),
  body            text not null,
  created_at      timestamptz default now()
);
create index if not exists idx_chat_messages_convo on public.chat_messages(conversation_id, created_at);

alter table public.chat_conversations enable row level security;
alter table public.chat_messages      enable row level security;

drop policy if exists convo_insert on public.chat_conversations;
create policy convo_insert on public.chat_conversations
  for insert with check (user_id = auth.uid());

drop policy if exists convo_select on public.chat_conversations;
create policy convo_select on public.chat_conversations
  for select using (user_id = auth.uid() or public.is_agent());

drop policy if exists convo_update on public.chat_conversations;
create policy convo_update on public.chat_conversations
  for update using (user_id = auth.uid() or public.is_agent())
            with check (user_id = auth.uid() or public.is_agent());

drop policy if exists msg_select on public.chat_messages;
create policy msg_select on public.chat_messages
  for select using (exists (
    select 1 from public.chat_conversations c
    where c.id = conversation_id and (c.user_id = auth.uid() or public.is_agent())));

drop policy if exists msg_insert on public.chat_messages;
create policy msg_insert on public.chat_messages
  for insert with check (
    (sender = 'visitor' and exists (
      select 1 from public.chat_conversations c
      where c.id = conversation_id and c.user_id = auth.uid()))
    or (sender in ('agent','bot') and public.is_agent())
  );

