  for select using (
    public.is_agent()
    or (active and (starts_at is null or starts_at <= now())
                and (ends_at  is null or ends_at  >  now()))
  );

drop policy if exists promos_agent_write on public.promos;
create policy promos_agent_write on public.promos
  for all using (public.is_agent()) with check (public.is_agent());

