-- =========================================================
-- 0) HELPER: ¿el usuario actual es un AGENTE?
--    Agente = usuario autenticado y NO anónimo. Los visitantes
--    del chat usan auth anónima (is_anonymous = true).
-- =========================================================
create or replace function public.is_agent()
returns boolean language sql stable as $$
  select coalesce(
    auth.role() = 'authenticated'
    and (auth.jwt() ->> 'is_anonymous')::boolean is not true,
  false);
$$;

